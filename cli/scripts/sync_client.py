#!/usr/bin/env python3
"""Regenerate cli/yoke_cli/client.py from backend/yoke_client.py.

Strips the canonical module's docstring and prepends a "do not edit"
header so the vendored copy is clearly identified as derived.

Invoked by `make sync-cli-client`.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
SRC = REPO_ROOT / "backend" / "yoke_client.py"
DST = REPO_ROOT / "cli" / "yoke_cli" / "client.py"

HEADER = '''"""Vendored copy of backend/yoke_client.py.

DO NOT EDIT THIS FILE BY HAND.
Run `make sync-cli-client` from the repo root to regenerate it after
changes to backend/yoke_client.py.
"""

# ruff: noqa
# fmt: off

'''


def main() -> int:
    if not SRC.exists():
        print(f"error: canonical source missing: {SRC}", file=sys.stderr)
        return 1
    content = SRC.read_text()
    # Drop the first top-of-file docstring; the vendored header replaces it.
    content_no_doc = re.sub(r'^""".*?"""\s*\n', "", content, count=1, flags=re.DOTALL)
    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text(HEADER + content_no_doc)
    print(f"✓ wrote {DST.relative_to(REPO_ROOT)} ({DST.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
